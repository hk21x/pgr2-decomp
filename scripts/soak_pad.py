#!/usr/bin/env python3
# PGR2's soak pad script (SOAK_PAD for sdk/scripts/soak.sh): from the title, Instant Action (a random city and car),
# the race loads, 60 seconds of throttle, pause, Quit, confirm, back on the title (about 115 seconds a cycle).
#   scripts/soak_pad.py <seconds>
import sys
secs = int(sys.argv[1])
end = secs * 60 + 2540  # vertical blanks (see scripts/pad/boot.txt)
print("# generated by scripts/soak.sh: Instant Action races back to back")
print("4760 START 30\n4910 START 20")
t = 5660  # the title menu, cursor on its first item
n = 0
while t + 6900 < end:
    n += 1
    print(f"# race {n}")
    print(f"{t} RIGHT 10\n{t + 100} RIGHT 10\n{t + 200} A 10")         # Instant Action
    print(f"{t + 2100} RT 3600")                                      # the race loads, then 60 s of throttle
    print(f"{t + 5800} START 10")                                     # pause: Continue . Retry . Quit
    print(f"{t + 5920} RIGHT 10\n{t + 6020} RIGHT 10\n{t + 6120} A 10")  # Quit
    print(f"{t + 6240} A 10")                                         # Quit Race? Yes
    t += 6900
